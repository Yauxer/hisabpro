-- Tout compte historique déjà mouvementé mais absent du référentiel devient un
-- compte historique de la société : aucun passé comptable n'est perdu/bloqué.
INSERT INTO comptes_societe(societe_id, numero, libelle, classe, type_compte, origine, actif)
SELECT e.societe_id, l.compte,
       COALESCE(MAX(NULLIF(BTRIM(l.libelle),'')), 'Compte historique ' || l.compte),
       CASE WHEN LEFT(l.compte,1) ~ '^[0-9]$' THEN LEFT(l.compte,1)::int ELSE 0 END,
       NULL, 'historique', TRUE
FROM lignes_ecriture l
JOIN ecritures e ON e.id = l.ecriture_id
LEFT JOIN comptes_societe cs ON cs.societe_id=e.societe_id AND cs.numero=l.compte
WHERE cs.id IS NULL AND l.compte ~ '^[0-9]{4,10}$'
GROUP BY e.societe_id, l.compte
ON CONFLICT (societe_id, numero) DO NOTHING;

CREATE OR REPLACE FUNCTION hisabpro_initialiser_plan_societe() RETURNS trigger AS $$
BEGIN
    INSERT INTO comptes_societe(societe_id, numero, libelle, classe, type_compte, origine, actif)
    SELECT NEW.id, numero, libelle, classe, type_compte, 'cgnc', TRUE
    FROM plan_comptable_cgnc_reference
    ON CONFLICT (societe_id, numero) DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_hisabpro_initialiser_plan_societe ON societes;
CREATE TRIGGER trg_hisabpro_initialiser_plan_societe
AFTER INSERT ON societes FOR EACH ROW EXECUTE FUNCTION hisabpro_initialiser_plan_societe();

-- 3) Garde-fou DB : même une écriture générée hors interface ne peut utiliser
-- un compte inexistant ou désactivé dans le plan de sa société.
CREATE OR REPLACE FUNCTION hisabpro_verifier_compte_societe() RETURNS trigger AS $$
DECLARE v_societe_id INTEGER;
BEGIN
    SELECT societe_id INTO v_societe_id FROM ecritures WHERE id = NEW.ecriture_id;
    IF v_societe_id IS NULL THEN
        RAISE EXCEPTION 'Écriture % introuvable pour la ligne comptable', NEW.ecriture_id;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM comptes_societe
        WHERE societe_id=v_societe_id AND numero=NEW.compte AND actif=TRUE
    ) THEN
        RAISE EXCEPTION 'Compte % absent ou désactivé dans le plan de la société %', NEW.compte, v_societe_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_hisabpro_verifier_compte_societe ON lignes_ecriture;
CREATE TRIGGER trg_hisabpro_verifier_compte_societe
BEFORE INSERT OR UPDATE OF compte, ecriture_id ON lignes_ecriture
FOR EACH ROW EXECUTE FUNCTION hisabpro_verifier_compte_societe();

COMMIT;
