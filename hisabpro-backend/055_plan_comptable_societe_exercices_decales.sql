BEGIN;

-- 1) Exercices : les dates réelles sont la source de vérité. `annee` désigne
-- l'année de clôture, ce qui permet notamment 01/07/2026 -> 30/06/2027 = exercice 2027.
ALTER TABLE exercices_comptables DROP CONSTRAINT IF EXISTS ck_exercice_meme_annee;
ALTER TABLE exercices_comptables DROP CONSTRAINT IF EXISTS ck_exercice_duree_max;
ALTER TABLE exercices_comptables DROP CONSTRAINT IF EXISTS ck_exercice_annee_reference_debut;
ALTER TABLE exercices_comptables DROP CONSTRAINT IF EXISTS ck_exercice_annee_reference_fin;

DO $$
BEGIN
    -- Douze mois calendaires, pas une durée fixe en jours :
    -- 01/01/2023 -> 31/12/2023 est valide mais 01/01/2023 -> 01/01/2024 ne l'est pas.
    -- Pour un début au 29/02, le 28/02 de l'année suivante reste la dernière date valide.
    IF EXISTS (
        SELECT 1
        FROM exercices_comptables
        WHERE date_fin > (
            (date_debut + INTERVAL '1 year')::date
            - CASE
                WHEN EXTRACT(MONTH FROM date_debut) = 2 AND EXTRACT(DAY FROM date_debut) = 29 THEN 0
                ELSE 1
              END
        )
    ) THEN
        RAISE EXCEPTION 'Patch 055 : au moins un exercice existant dépasse douze mois calendaires. Corrigez ses dates avant migration.';
    END IF;
    IF EXISTS (SELECT 1 FROM exercices_comptables WHERE EXTRACT(YEAR FROM date_fin)::int <> annee) THEN
        RAISE EXCEPTION 'Patch 055 : une année de référence existante ne correspond pas à son année de clôture. Corrigez la période avant migration.';
    END IF;
END $$;

ALTER TABLE exercices_comptables
    ADD CONSTRAINT ck_exercice_duree_max CHECK (
        date_fin <= (
            (date_debut + INTERVAL '1 year')::date
            - CASE
                WHEN EXTRACT(MONTH FROM date_debut) = 2 AND EXTRACT(DAY FROM date_debut) = 29 THEN 0
                ELSE 1
              END
        )
    ),
    ADD CONSTRAINT ck_exercice_annee_reference_fin CHECK (EXTRACT(YEAR FROM date_fin)::int = annee);

-- 2) Référentiel CGNC livré + plan effectivement utilisé par chaque société.
CREATE TABLE IF NOT EXISTS plan_comptable_cgnc_reference (
    numero VARCHAR(10) PRIMARY KEY,
    libelle VARCHAR(300) NOT NULL,
    classe INTEGER NOT NULL CHECK (classe BETWEEN 0 AND 9),
    type_compte VARCHAR(10)
);

CREATE TABLE IF NOT EXISTS comptes_societe (
    id SERIAL PRIMARY KEY,
    societe_id INTEGER NOT NULL REFERENCES societes(id) ON DELETE CASCADE,
    numero VARCHAR(10) NOT NULL,
    libelle VARCHAR(300) NOT NULL,
    classe INTEGER NOT NULL CHECK (classe BETWEEN 0 AND 9),
    type_compte VARCHAR(10),
    origine VARCHAR(20) NOT NULL DEFAULT 'cgnc' CHECK (origine IN ('cgnc','personnalise','historique')),
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP DEFAULT NOW(),
    CONSTRAINT uq_compte_societe_numero UNIQUE (societe_id, numero),
    CONSTRAINT ck_compte_societe_numero CHECK (numero ~ '^[0-9]{4,10}$')
);
CREATE INDEX IF NOT EXISTS ix_comptes_societe_societe_actif ON comptes_societe(societe_id, actif);
CREATE INDEX IF NOT EXISTS ix_comptes_societe_numero ON comptes_societe(numero);

