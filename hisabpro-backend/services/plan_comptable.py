def _type_compte_par_numero(numero: str) -> str:
    """Type d'affichage de repli lorsque la migration 055 n'a pas encore chargé
    les métadonnées du référentiel. Le numéro et le libellé restent la source
    normative ; ce code n'influence jamais les calculs comptables.
    """
    n = str(numero or "")
    if n.startswith("0"): return "SP"
    if n.startswith("1"): return "CP"
    if n.startswith("28") or n.startswith("29"): return "AM"
    if n.startswith("2"): return "AI"
    if n.startswith("31"): return "ST"
    if n.startswith("3"): return "AC"
    if n.startswith("4"): return "PC"
    if n.startswith("5"): return "TR"
    if n.startswith("6"): return "CH"
    if n.startswith("7"): return "PD"
    if n.startswith("8"): return "RE"
    return "SP"


def assurer_plan_societe(db, societe_id: int):
    """Complète le plan d'une société depuis le référentiel CGNC en lecture seule.

    Le référentiel partagé appartient aux migrations (055), pas aux requêtes
    HTTP : le compte PostgreSQL de l'application a seulement SELECT dessus.
    Il peut en revanche insérer les comptes manquants dans le plan de la société.
    """
    import models

    refs = db.query(models.CompteCGNCReference).all()
    if not refs:
        raise RuntimeError(
            "Référentiel CGNC vide : exécutez la migration 055 "
            "avant d'utiliser le plan comptable."
        )

    existants = {row[0] for row in db.query(models.CompteSociete.numero).filter(
        models.CompteSociete.societe_id == societe_id
    ).all()}
    ajouts = [models.CompteSociete(
        societe_id=societe_id, numero=r.numero, libelle=r.libelle, classe=r.classe,
        type_compte=r.type_compte, origine="cgnc", actif=True,
    ) for r in refs if r.numero not in existants]
    if ajouts:
        db.add_all(ajouts)
        db.flush()
    return db.query(models.CompteSociete).filter(
        models.CompteSociete.societe_id == societe_id
    )


def libelle_compte(compte: str, db=None, societe_id: int | None = None) -> str | None:
    numero = str(compte or "").strip()
    if db is not None and societe_id is not None:
        try:
            import models
            row = db.query(models.CompteSociete).filter_by(
                societe_id=societe_id, numero=numero
            ).first()
            if row:
                return row.libelle
        except Exception:
            # Compatibilité avec les bases n'ayant pas encore reçu la migration.
            pass
    return PLAN_COMPTABLE.get(numero)


def compte_utilisable(db, societe_id: int, numero: str) -> bool:
    import models
    assurer_plan_societe(db, societe_id)
    return db.query(models.CompteSociete.id).filter_by(
        societe_id=societe_id, numero=str(numero or "").strip(), actif=True
    ).first() is not None
