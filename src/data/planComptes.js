export function rechercherCompte(query) {
  const q = query.toLowerCase().trim()
  if (!q) return []
  return PLAN_COMPTES.filter(
    c => c.compte.startsWith(q) || c.libelle.toLowerCase().includes(q)
  ).slice(0, 10)
}

export function trouverCompte(numero) {
  return PLAN_COMPTES.find(c => c.compte === numero) || null
}

export function comptesParClasse(num) {
  return PLAN_COMPTES.filter(c => c.classe === num)
}


// Patch 055 : le tableau reste la source de repli au démarrage, puis il est
// remplacé en mémoire par le plan actif de la société connecté. Les imports
// existants conservent ainsi la même référence de tableau.
export function remplacerPlanComptes(comptes = []) {
  if (!Array.isArray(comptes) || !comptes.length) return
  const normalises = comptes
    .filter(c => c && (c.compte || c.numero) && c.actif !== false)
    .map(c => ({
      compte: String(c.compte || c.numero),
      libelle: String(c.libelle || ''),
      classe: Number(c.classe ?? String(c.compte || c.numero)[0] ?? 0),
      type: c.type || c.type_compte || 'SP',
      origine: c.origine || 'cgnc',
      actif: c.actif !== false,
    }))
    .sort((a, b) => a.compte.localeCompare(b.compte))
  // Préserver la référence existante et ne notifier les composants que si
  // un compte a réellement changé (évite les remontages après chaque refresh).
  const inchange = PLAN_COMPTES.length === normalises.length && PLAN_COMPTES.every((ancien, i) => {
    const nouveau = normalises[i]
    return ancien.compte === nouveau.compte && ancien.libelle === nouveau.libelle &&
      ancien.classe === nouveau.classe && ancien.type === nouveau.type &&
      ancien.origine === nouveau.origine && ancien.actif === nouveau.actif
  })
  if (inchange) return false
  PLAN_COMPTES.splice(0, PLAN_COMPTES.length, ...normalises)
  return true
}
